# 모든 코어가 0x80000000에서 동시에 이 코드를 실행한다 (링커 스크립트가 맨 앞에 배치).
# 아직 스택을 설정하지 않았으므로 스택을 쓰는 코드(함수 호출 등)는 넣지 않는다.
.section .text.entry
.global _start
_start:
    # UART(NS16550) 송신 레지스터는 메모리 맵 입출력: 이 주소에 한 바이트를 쓰면 글자가 나간다.
    li t0, 0x10000000
    li t1, 'A'
    sb t1, 0(t0)
1:
    # 할 일이 없는 코어는 전력을 아끼며 대기한다.
    wfi
    j 1b
